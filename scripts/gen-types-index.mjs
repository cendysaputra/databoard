// Rebuilds src/shared/types/index.ts from the files ts-rs generated (`npm run gen:types`).
import { readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const dir = fileURLToPath(new URL('../src/shared/types/', import.meta.url));
const names = readdirSync(dir)
  .filter((file) => file.endsWith('.ts') && file !== 'index.ts')
  .map((file) => file.slice(0, -3))
  .sort();

const lines = names.map((name) => `export type { ${name} } from './${name}';`);
writeFileSync(
  `${dir}index.ts`,
  `// Generated by scripts/gen-types-index.mjs. Do not edit.\n${lines.join('\n')}\n`,
);
console.log(`types: ${names.length} exported`);
